function normalizeStadiumName(value) {
  return String(value || '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
}
function findStadiumDetails(visit) {
  const name = normalizeStadiumName(visit.stadium);
  const iso = String(visit.iso || '').toUpperCase();
  return stadiumCatalog.find(stadium => stadium.iso === iso && [stadium.name, ...(stadium.aliases || [])].some(alias => normalizeStadiumName(alias) === name));
}
function enrichStadium(visit) {
  const details = findStadiumDetails(visit);
  const empty = value => value == null || String(value).trim() === '';
  if (!details || !Number.isFinite(details.lat) || !Number.isFinite(details.lng) || !empty(visit.lat) || !empty(visit.lng)) return visit;
  return {...visit, lat: details.lat, lng: details.lng, coordinateSource: details.coordinateSource};
}
